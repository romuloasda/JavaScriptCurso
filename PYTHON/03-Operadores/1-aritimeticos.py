# OPERADORES ARITMÉTICOS EM PYTHON
# ==========================================

# 1. Adição (+)
# Soma dois valores.
soma = 10 + 5
print(f"Adição (10 + 5): {soma}")

# 2. Subtração (-)
# Subtrai o segundo valor do primeiro.
subtracao = 10 - 5
print(f"Subtração (10 - 5): {subtracao}")

# 3. Multiplicação (*)
# Multiplica dois valores.
multiplicacao = 10 * 5
print(f"Multiplicação (10 * 5): {multiplicacao}")

# 4. Divisão (/)
# Divide o primeiro valor pelo segundo. Sempre retorna um número decimal (float).
divisao = 10 / 4
print(f"Divisão (10 / 4): {divisao}")

# 5. Divisão Inteira (//)
# Divide os números e descarta a parte decimal, retornando apenas o número inteiro.
divisao_inteira = 10 // 4
print(f"Divisão Inteira (10 // 4): {divisao_inteira}")

# 6. Módulo (%)
# Retorna o resto da divisão entre dois números. Muito útil para descobrir se um número é par ou ímpar.
modulo = 10 % 3
print(f"Módulo/Resto (10 % 3): {modulo}")

# 7. Exponenciação (**)
# Eleva o primeiro número (base) à potência do segundo número (expoente).
exponenciacao = 2 ** 3
print(f"Exponenciação (2 ** 3): {exponenciacao}")