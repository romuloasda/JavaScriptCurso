# Listas são estruturas indexadas
# indices->0, 1, 2, 3

numeros = [1, 2, 3, 4,]
print(numeros)

frutas = ['maça', 'banana', 'laranja']
print(frutas)

misto = [1, True, 3.14, [1,2,3], 'João']
print(misto)

# Pode acessar o elemento pelo indice
print(numeros[3])
print(frutas[1])
print(misto[3][2])
# Do fim pri inicio
print(frutas[-3])

